// Indian construction domain knowledge, applied deterministically.
//
// The layering this enables:
//   1. rules here decode what they can, for free and with certainty
//   2. the AI pass is asked ONLY about the residue
//   3. geometry verifies both  (see `verify.ts`)
//
// Nothing here produces a quantity.
import type { CadLabel } from '../../cad/types';
import { decodeElectrical } from './electrical';

